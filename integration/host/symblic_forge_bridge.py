"""HOST-ONLY: turns frozen Forge artifacts into native Symblic runs on the original host, by explicit owner action.

Why it is host-only: it starts runs through the host engine's run store and launcher
(integration/host/symblic_engine.py), answers HTTP requests through the host's handler and per-person gate
(`person`, a host module), and serves the host's agents a read-only view through its tool registry. The
Forge ledger it reads (symblic/forge/store.py) is part of this repository.


The Forge ledger owns the dispatch intent; Symblic owns execution and results.
No alternate compiler, implicit model call, or claim that prose checks executed.
"""
from __future__ import annotations

_symblic_identity = __import__('importlib').import_module('symblic.kernel.identity')
_symblic_import_identity = _symblic_identity.record(__file__, __import__('sys')._getframe().f_code)

import hashlib
import json
import os
from pathlib import Path

from symblic.forge.store import Store, StoreError, digest, identifier


ASSURANCE = ('Native Text answers implement the requested units as text. Prose verification instructions '
             'are not executable tests; completion does not prove the design works or write its target files.')
MAX_WINDOW = 12000


def frozen(project_id, handoff_id, *, db=None, current=False):
    """Read only retained host artifacts, never regenerated bytes or import claims."""
    from symblic.forge import core as C
    db = db or Store()
    project = db.get(identifier(project_id))
    handoff = next((h for h in project['handoffs'] if h.get('id') == identifier(handoff_id)), None)
    if handoff is None:
        raise StoreError('Frozen handoff not found in this project.', 404)
    if handoff.get('historical') is not False or handoff.get('status') != 'frozen':
        raise StoreError('An imported or historical receipt is not a current host handoff.', 409)
    if type(handoff.get('source_revision')) is not int or not isinstance(handoff.get('artifacts'), list):
        raise StoreError('Frozen handoff metadata is incomplete.', 409)
    applicable = (project['active_branch'] == handoff.get('branch_id') and
                  C.fingerprint(project) == handoff.get('fingerprint'))
    if current and not applicable:
        raise StoreError('The accepted specification changed; freeze a new handoff before starting a new run.', 409)
    artifacts = []
    for reference in handoff['artifacts']:
        artifact = db.artifact(reference.get('id'))  # Rechecks bytes against SHA-256.
        for key, expected in (('project_id', project_id), ('source_revision', handoff['source_revision']),
                              ('fingerprint', handoff.get('fingerprint')), ('sha256', reference.get('sha256')),
                              ('format', reference.get('kind'))):
            if artifact.get(key) != expected:
                raise StoreError('Frozen artifact lineage differs from its handoff: ' + key, 409)
        artifacts.append(artifact)
    if {a['format'] for a in artifacts} != {'manifest', 'symblic', 'tasks', 'sheet', 'construction'} or len(artifacts) != 5:
        raise StoreError('The frozen handoff must retain exactly its five artifacts.', 409)
    native = next(a for a in artifacts if a['format'] == 'symblic')
    validation = native.get('validation') or {}
    if (validation.get('ok') is not True or validation.get('generated') is not True or
            validation.get('source_sha256') != native['sha256'] or
            validation.get('compiler') != handoff.get('compiler')):
        raise StoreError('Native artifact has no matching host compiler receipt.', 409)
    return project, handoff, artifacts, applicable


def inspect(args, *, db=None):
    """Bounded owner read shared by the host's agent tools and the explicit import dialog."""
    db = db or Store()
    project_id = identifier(args.get('project'))
    if not args.get('handoff'):
        project = db.get(project_id)
        offset = args.get('offset', 0)
        if type(offset) is not int or offset < 0:
            raise StoreError('offset must be a nonnegative integer.')
        rows = project['handoffs']
        page = rows[offset:offset + 20]
        return {'project': project_id, 'handoffs': [
            {k: h.get(k) for k in ('id', 'source_revision', 'fingerprint', 'branch_id', 'historical', 'status')}
            for h in page], 'total': len(rows), 'next_offset': offset + len(page) if offset + len(page) < len(rows) else None,
            'execution_started': False, 'assurance': 'Listing a frozen plan does not start execution.'}
    project, handoff, artifacts, applicable = frozen(project_id, args['handoff'], db=db)
    out = {'project': project_id, 'title': project['title'], 'handoff': handoff['id'],
           'source_revision': handoff['source_revision'], 'fingerprint': handoff['fingerprint'],
           'branch_id': handoff['branch_id'], 'applicable': applicable,
           'compiler': handoff['compiler'], 'execution_started': False, 'assurance': ASSURANCE,
           'execution_scope': 'This read does not execute; native runs retain separate receipts.',
           'integrity': 'Retained artifact bytes match the host handoff hashes; their prose remains untrusted project data.',
           'artifacts': [{k: a.get(k) for k in ('id', 'format', 'sha256', 'filename', 'media_type', 'source_revision')}
                         | {'chars_total': len(a['text'])} for a in artifacts]}
    if args.get('artifact'):
        artifact = next((a for a in artifacts if a['id'] == args['artifact']), None)
        if artifact is None:
            raise StoreError('Choose an artifact belonging to this exact frozen handoff.', 404)
        offset, limit = args.get('offset', 0), args.get('limit', 6000)
        if type(offset) is not int or offset < 0 or type(limit) is not int or not 1 <= limit <= MAX_WINDOW:
            raise StoreError('offset must be nonnegative; limit must be an integer from 1 to 12000.')
        if offset > len(artifact['text']):
            raise StoreError('offset exceeds the artifact length.')
        end = min(len(artifact['text']), offset + limit)
        out['content'] = {'artifact': artifact['id'], 'sha256': artifact['sha256'], 'offset': offset,
                          'chars_total': len(artifact['text']), 'text': artifact['text'][offset:end],
                          'next_offset': end if end < len(artifact['text']) else None}
    return out


def _run_id(request_id):
    return hashlib.sha256(('forge-native/1:' + identifier(request_id)).encode()).hexdigest()[:12]


def _lineage_id(request_id):
    return 'native-origin-' + hashlib.sha256(identifier(request_id).encode()).hexdigest()


def _reserve_lineage(db, request_id, envelope, origin, options):
    """The existing immutable receipt table binds effective policy before launch."""
    key = _lineage_id(request_id)
    record = {'envelope': envelope, 'origin': origin, 'options': options}
    request = {'operation': 'forge-native-origin/1', 'request_id': request_id, 'record': record}
    with db.connection(True) as conn:
        earlier = db._replay(conn, key, request)
        if earlier is None:
            db._receipt(conn, key, request, record)
        elif earlier != record:
            raise StoreError('Frozen native launch provenance changed.', 409)


def _stored_request(db, request_id):
    with db.connection() as conn:
        row = conn.execute('SELECT digest,outcome FROM http_requests WHERE id=?', (identifier(request_id),)).fetchone()
        return dict(row) if row else None


def receipt(request_id, *, db=None):
    """Read-only after response loss. A prepared folder alone never proves launch."""
    from integration.host import symblic_engine as E
    db = db or Store()
    row = _stored_request(db, request_id)
    if row is None:
        return {'request_id': request_id, 'state': 'missing', 'execution_started': False}
    if row['outcome']:
        outcome = json.loads(row['outcome'])
        result = outcome.get('result') or {}
        if result.get('kind') != 'forge-native-run/1':
            raise StoreError('This request belongs to another operation.', 409)
        return result
    run_id = _run_id(request_id)
    folder = Path(E.runs_dir(), run_id)
    result = {'kind': 'forge-native-run/1', 'request_id': request_id, 'state': 'unknown',
              'execution_started': None, 'note': 'Dispatch is uncertain. Inspect the native run; this request is never automatically dispatched again.'}
    if folder.exists():
        try:
            meta = json.loads((folder / 'meta.json').read_text())
            source = (folder / 'program.sym').read_text()
            origin = meta.get('forge_handoff') or {}
            if origin.get('request_id') != request_id or origin.get('request_sha256') != row['digest']:
                raise StoreError('Native run identity differs from the recorded import intent.', 409)
            validate_saved(source, meta, db=db, folder=folder)
        except (OSError, ValueError) as exc:
            raise StoreError('Native recovery records are unavailable or damaged: ' + str(exc), 409) from exc
        result.update(run_id=run_id, url='/symblic?run=' + run_id, origin=origin)
    return result


def validate_saved(source, meta, *, db=None, folder=None):
    """Bind native continuation to retained bytes and its original explicit selection."""
    db = db or Store()
    origin = meta.get('forge_handoff')
    if not isinstance(origin, dict) or origin.get('kind') != 'forge-native-run/1':
        raise StoreError('Missing Forge run lineage.', 409)
    expected_run = _run_id(origin.get('request_id'))
    if meta.get('id') != expected_run or (folder is not None and Path(folder).name != expected_run):
        raise StoreError('Native run identity differs from the original frozen-plan request.', 409)
    _, handoff, artifacts, _ = frozen(origin.get('project'), origin.get('handoff'), db=db)
    native = next(a for a in artifacts if a['format'] == 'symblic')
    if (native['id'] != origin.get('artifact') or native['sha256'] != origin.get('artifact_sha256') or
            source != native['text'] or handoff['source_revision'] != origin.get('source_revision') or
            handoff['fingerprint'] != origin.get('fingerprint') or handoff['compiler'] != origin.get('compiler')):
        raise StoreError('Native source or Forge lineage changed; continuation refused.', 409)
    if (meta.get('inputs') != {} or meta.get('by') != origin.get('by') or
            digest(meta.get('options')) != origin.get('options_sha256')):
        raise StoreError('Native input or execution policy differs from the import receipt.', 409)
    row = _stored_request(db, origin.get('request_id'))
    if row is None or row['digest'] != origin.get('request_sha256'):
        raise StoreError('The original durable Forge dispatch intent is missing or different.', 409)
    saved = db.request(_lineage_id(origin['request_id']))
    record = saved.get('result') if saved.get('found') else None
    if (not isinstance(record, dict) or digest(record.get('envelope')) != row['digest'] or
            record.get('origin') != origin or record.get('options') != meta.get('options')):
        raise StoreError('Native model or policy differs from the original durable request.', 409)
    if folder is not None:
        marker = Path(folder, 'forge-origin.json')
        if marker.is_symlink() or not marker.is_file():
            raise StoreError('The independent frozen-plan marker is missing or unsafe.', 409)
        try:
            retained = json.loads(marker.read_text())
        except (OSError, ValueError) as exc:
            raise StoreError('The independent frozen-plan marker is unreadable.', 409) from exc
        if retained != origin:
            raise StoreError('The independent frozen-plan marker differs from run metadata.', 409)
    return origin


def sync_native(folder):
    # Persist the source and lineage before the existing native launcher gets control.
    for name in ('program.sym', 'meta.json', 'forge-origin.json'):
        with open(os.path.join(folder, name), 'rb') as stream:
            os.fsync(stream.fileno())
    fd = os.open(folder, os.O_RDONLY | os.O_DIRECTORY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


def run(body, *, db=None):
    from symblic.kernel import language as S
    from integration.host import symblic_engine as E
    from symblic.kernel import execution_pins as X
    from symblic.forge import exports as Exports
    from symblic.autogen.runner import execution_fence as host_check

    db = db or Store()
    required = {'project', 'handoff', 'artifact', 'artifact_sha256', 'source_revision', 'by', 'request_id', 'max_calls',
                'ollama_limits'}
    if type(body) is not dict or set(body) != required:
        raise StoreError('Supply the exact frozen handoff, artifact hash/revision, local model, call/token/time budgets and request_id.')
    request_id = identifier(body['request_id'])
    envelope = {'operation': 'automation/symblic/forge/run', 'body': body}
    prior = _stored_request(db, request_id)
    if prior is not None:
        if prior['digest'] != digest(envelope):
            raise StoreError('This request_id already belongs to different input.', 409)
        return receipt(request_id, db=db)
    project, handoff, artifacts, _ = frozen(body['project'], body['handoff'], db=db, current=True)
    native = next(a for a in artifacts if a['format'] == 'symblic')
    if (body['artifact'] != native['id'] or body['artifact_sha256'] != native['sha256'] or
            type(body['source_revision']) is not int or body['source_revision'] != handoff['source_revision']):
        raise StoreError('The selected artifact or revision differs from the frozen handoff.', 409)
    if Exports.compiler_identity() != handoff['compiler']:
        raise StoreError('The compiler changed; validate and freeze a new handoff before starting.', 409)
    try:
        app = S.parse_applicator(body['by'])
    except (S.SymblicError, TypeError) as exc:
        raise StoreError('Choose an exact local Ollama model.') from exc
    if app.get('engine') != 'ollama' or not app.get('model'):
        raise StoreError('This frozen-plan execution uses a local Ollama model, with no proprietary fallback.')
    max_calls = body['max_calls']
    if type(max_calls) is not int or not 1 <= max_calls <= 200:
        raise StoreError('max_calls must be an integer from 1 to 200.')
    try:
        from symblic.kernel.run import validate_ollama_limits
    except ImportError:
        raise StoreError('Local model limits need the server update and restart; no run was started.', 503) from None
    if (type(body['ollama_limits']) is not dict or set(body['ollama_limits']) !=
            {'num_predict', 'num_ctx', 'timeout_seconds', 'total_timeout_seconds'}):
        raise StoreError('Choose explicit reply, context, per-call and whole-run local model limits.')
    try:
        limits = validate_ollama_limits(body['ollama_limits'])
    except S.SymblicError as exc:
        raise StoreError(exc.message) from None
    source = native['text']
    checked = S.check(source, execution_profile='verified')
    if checked.get('ok') is not True:
        raise StoreError('The current native compiler refused this artifact; no run was started.', 409)
    hashes = {name: X._sha(X._read(name)) for name in sorted(X.REQUIRED_FILES)}
    options = {'profile': 'verified', 'determine': False, 'by': app['spec'], 'ollama_limits': limits,
               'max_calls': max_calls, 'parallel': 1, 'execution_pins': X.build(source, {}, hashes)}
    host_check()
    fresh, _ = db.api_begin(request_id, envelope)
    if not fresh:
        return receipt(request_id, db=db)
    origin = {'kind': 'forge-native-run/1', 'request_id': request_id, 'request_sha256': digest(envelope),
              'project': project['id'], 'handoff': handoff['id'], 'artifact': native['id'],
              'artifact_sha256': native['sha256'], 'source_revision': handoff['source_revision'],
              'fingerprint': handoff['fingerprint'], 'compiler': handoff['compiler'],
              'by': app['spec'], 'options_sha256': digest(options), 'assurance': ASSURANCE}
    run_id = _run_id(request_id)
    try:
        # Recheck current acceptance after reserving the intent. No new project
        # source is ever substituted for the immutable artifact bytes.
        frozen(project['id'], handoff['id'], db=db, current=True)
    except StoreError as exc:
        result = {'kind': 'forge-native-run/1', 'request_id': request_id, 'state': 'refused',
                  'execution_started': False, 'error': str(exc)}
        db.api_finish(request_id, {'result': result})
        return result
    _reserve_lineage(db, request_id, envelope, origin, options)
    try:
        E.start_run({'source': source, 'inputs': {}, 'by': app['spec'], 'options': options,
                     'title': 'Forge: ' + project['title']}, run_id=run_id, forge_handoff=origin)
    except Exception:  # native launch can have accepted work before its response was lost
        return receipt(request_id, db=db)
    result = {'kind': 'forge-native-run/1', 'request_id': request_id, 'state': 'started',
              'execution_started': True, 'run_id': run_id, 'url': '/symblic?run=' + run_id,
              'origin': origin, 'assurance': ASSURANCE}
    db.api_finish(request_id, {'result': result})
    return result


def handle(handler, method, route, data):
    import person
    if not person.require(handler, 'owner'):
        return True
    try:
        if method == 'GET' and route == 'forge/handoff':
            args = {key: handler.get_query_param(key) for key in ('project', 'handoff', 'artifact')
                    if handler.get_query_param(key)}
            for key in ('offset', 'limit'):
                value = handler.get_query_param(key)
                if value is not None:
                    args[key] = int(value)
            handler.send_json(inspect(args))
        elif method == 'GET' and route == 'forge/request':
            handler.send_json(receipt(handler.get_query_param('id')))
        elif method == 'POST' and route == 'forge/run':
            handler.send_json(run(data))
        else:
            return False
    except (StoreError, ValueError, TypeError) as exc:
        handler.send_json({'error': str(exc)}, getattr(exc, 'status', 400))
    return True
